import csv
import os.path as osp
from collections import OrderedDict
from pathlib import Path

import numpy as np
import pandas as pd
from mmcv.utils import print_log

from ..utils import get_root_logger
from .base import BaseDataset
from .builder import DATASETS


LABEL_COL = 'MDS-UPDRS_score_3.9 _arising_from_chair'


def _default_label_workbook():
    repo_root = Path(__file__).resolve().parents[2]
    label_dir = repo_root / 'data' / 'REMAP' / 'SitToStand' / 'Data' / 'STS_human_labels'
    preferred = label_dir / '.~SitToStand_human_labels.xls'
    fallback = label_dir / 'SitToStand_human_labels.xls'
    if preferred.exists() and preferred.stat().st_size > 0:
        return preferred
    return fallback


def _load_skeleton_sequence(csv_path):
    df = pd.read_csv(csv_path, comment='#', header=None)
    if df.shape[1] < 2 + 25 * 2:
        raise ValueError(f'Unexpected column count in {csv_path}: {df.shape[1]}')
    frames = df.iloc[:, 0].to_numpy(dtype=np.int64)
    coords = df.iloc[:, 2:2 + 25 * 2].to_numpy(dtype=np.float32).reshape(-1, 25, 2)
    visible = ~np.any(coords == 0, axis=-1)
    keypoint_score = visible.astype(np.float32)
    keypoint = coords[None]
    keypoint_score = keypoint_score[None]
    return frames, keypoint, keypoint_score


def _sequence_name_from_row(row):
    if 'file' in row and isinstance(row['file'], str) and row['file']:
        return osp.splitext(row['file'])[0]
    transition_id = int(row['Transition ID'])
    participant = int(row['Participant ID number'])
    cohort = str(row['PD_or_C']).strip()
    return f'Pt{participant}_{cohort}_n_{transition_id}'


def _read_split_csv(path):
    rows = []
    with open(path, newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            rows.append(row)
    return rows


@DATASETS.register_module()
class RemapSitToStandDataset(BaseDataset):
    """REMAP Sit-to-Stand skeleton dataset.

    The dataset can be loaded from:
    - split CSV files generated by `tools/build_remap_splits.py`
    - the original Excel workbook for metadata inspection
    """

    def __init__(self,
                 ann_file,
                 pipeline,
                 skeleton_dir=None,
                 label_file=None,
                 label_col=LABEL_COL,
                 min_frames=1,
                 **kwargs):
        self.skeleton_dir = Path(skeleton_dir) if skeleton_dir is not None else None
        self.label_file = Path(label_file) if label_file is not None else _default_label_workbook()
        self.label_col = label_col
        self.min_frames = min_frames
        super().__init__(ann_file, pipeline, start_index=0, modality='Pose', **kwargs)

        logger = get_root_logger()
        logger.info(f'{len(self)} REMAP SitToStand sequences loaded')

    def _load_from_split_csv(self):
        rows = _read_split_csv(self.ann_file)
        data = []
        for row in rows:
            label = row.get('label', None)
            if label is None or label == '' or str(label).lower() == 'nan':
                continue
            frame_dir = row.get('frame_dir') or _sequence_name_from_row(row)
            csv_name = row.get('file', f'{frame_dir}.csv')
            csv_path = self.skeleton_dir / csv_name if self.skeleton_dir is not None else Path(csv_name)
            if not csv_path.exists():
                continue

            _, keypoint, keypoint_score = _load_skeleton_sequence(csv_path)
            if keypoint.shape[1] < self.min_frames:
                continue

            data.append(dict(
                frame_dir=frame_dir,
                total_frames=int(keypoint.shape[1]),
                label=int(float(label)),
                subject=str(row.get('participant_id', row.get('Participant ID number', ''))),
                patient_id=str(row.get('participant_id', row.get('Participant ID number', ''))),
                cohort=str(row.get('PD_or_C', row.get('cohort', ''))),
                transition_id=str(row.get('transition_id', row.get('Transition ID', ''))),
                file=csv_name,
                keypoint=keypoint,
                keypoint_score=keypoint_score,
            ))
        return data

    def _load_from_workbook(self):
        if not self.label_file.exists():
            raise FileNotFoundError(self.label_file)
        df = pd.read_excel(self.label_file)
        if self.label_col not in df.columns:
            raise KeyError(f'Label column not found: {self.label_col}')

        data = []
        for _, row in df.iterrows():
            label = row[self.label_col]
            if pd.isna(label):
                continue
            frame_dir = _sequence_name_from_row(row)
            csv_name = f'{frame_dir}.csv'
            csv_path = self.skeleton_dir / csv_name if self.skeleton_dir is not None else Path(csv_name)
            if not csv_path.exists():
                continue

            _, keypoint, keypoint_score = _load_skeleton_sequence(csv_path)
            if keypoint.shape[1] < self.min_frames:
                continue

            participant = int(row['Participant ID number'])
            cohort = str(row['PD_or_C']).strip()
            transition_id = int(row['Transition ID'])
            data.append(dict(
                frame_dir=frame_dir,
                total_frames=int(keypoint.shape[1]),
                label=int(label),
                subject=str(participant),
                patient_id=str(participant),
                cohort=cohort,
                transition_id=str(transition_id),
                file=csv_name,
                keypoint=keypoint,
                keypoint_score=keypoint_score,
            ))
        return data

    def load_annotations(self):
        assert self.ann_file.endswith(('.csv', '.xls'))
        if self.ann_file.endswith('.csv'):
            return self._load_from_split_csv()
        return self._load_from_workbook()

    def evaluate(self, results, metrics=None, logger=None, **deprecated_kwargs):
        if not isinstance(results, list):
            raise TypeError(f'results must be a list, but got {type(results)}')
        assert len(results) == len(self), (
            f'The length of results is not equal to the dataset len: '
            f'{len(results)} != {len(self)}')

        metrics = metrics if metrics is not None else ['accuracy', 'precision', 'recall', 'f1_score', 'confusion_matrix']
        metrics = metrics if isinstance(metrics, (list, tuple)) else [metrics]
        allowed_metrics = ['accuracy', 'precision', 'recall', 'f1_score', 'confusion_matrix']
        for metric in metrics:
            if metric not in allowed_metrics:
                raise KeyError(f'metric {metric} is not supported')

        if len(results) > 0 and isinstance(results[0], (tuple, list)):
            scores = np.stack([np.asarray(result[0], dtype=np.float32) for result in results])
        else:
            scores = np.stack([np.asarray(result, dtype=np.float32) for result in results])

        labels = np.asarray([ann['label'] for ann in self.video_infos], dtype=np.int64)
        pred = scores.argmax(axis=1)
        num_classes = int(self.num_classes or max(labels.max(), pred.max()) + 1)
        cm = np.zeros((num_classes, num_classes), dtype=np.int64)
        for gt, pr in zip(labels, pred):
            cm[int(gt), int(pr)] += 1

        tp = np.diag(cm).astype(np.float32)
        fp = cm.sum(axis=0).astype(np.float32) - tp
        fn = cm.sum(axis=1).astype(np.float32) - tp
        precision_per_class = np.divide(tp, tp + fp, out=np.zeros_like(tp), where=(tp + fp) > 0)
        recall_per_class = np.divide(tp, tp + fn, out=np.zeros_like(tp), where=(tp + fn) > 0)
        f1_per_class = np.divide(
            2 * precision_per_class * recall_per_class,
            precision_per_class + recall_per_class,
            out=np.zeros_like(tp),
            where=(precision_per_class + recall_per_class) > 0,
        )

        eval_results = OrderedDict()
        if 'accuracy' in metrics:
            eval_results['accuracy'] = float((pred == labels).mean())
        if 'precision' in metrics:
            eval_results['precision'] = float(precision_per_class.mean())
        if 'recall' in metrics:
            eval_results['recall'] = float(recall_per_class.mean())
        if 'f1_score' in metrics:
            eval_results['f1_score'] = float(f1_per_class.mean())

        log_prefix = '\nEvaluating REMAP severity classification ...'
        print_log(log_prefix, logger=logger)
        for key, value in eval_results.items():
            print_log(f'{key}\t{value:.4f}', logger=logger)
        if 'confusion_matrix' in metrics:
            print_log('confusion_matrix (rows=gt, cols=pred):', logger=logger)
            for row_idx, row in enumerate(cm):
                print_log(f'class_{row_idx}: {row.tolist()}', logger=logger)

        return eval_results
